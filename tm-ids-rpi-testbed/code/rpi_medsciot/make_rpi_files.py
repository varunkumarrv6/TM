"""Generates everything the Raspberry Pi setup needs (MedSec-25, 3 weighted TMs, 4-bit weight nibbles):

  test set (same style as iot_dataset/rpi_50_test):
    X_50.npy / X_50_bitpacked.npy / X_50.bin   50 test flows, 178 Boolean features, LSB-first, 23 bytes per flow
    y_50_actual.npy / actual.bin              true class of each flow (1 byte each)
    y_50_tm_predictions.npy / tmu_pred.bin    prediction of the deployed 3-TM model (no attack) -> reference
    class_names.npy / class_names.txt          class id -> name
  split packet streams, one per sending RPi (UDP datagrams written back to back):
    tm0_hamming.bin, tm1_hamming.bin, tm2_hamming.bin     Hamming(7,4)   (956-byte datagrams)
    tm0_raw.bin,     tm1_raw.bin,     tm2_raw.bin         no ECC         (548-byte datagrams)
  rpi_medsciot_config.h    constants for the C receiver (generated, do not edit)

Datagram (same as medsciot/ecc_pipeline.py and rpi_customarchi.c):
  [0] weight nibble (bits 7-4, signed -8..7) | class nibble (bits 3-0)
  [1] seq low  [2] seq high  [3] TM node id
  payload = Hamming(7,4)( 12 rules x 45 bytes + copy of the 4 header bytes )   544 -> 952 bytes
  Hamming: byte -> high nibble codeword, low nibble codeword; nibble bit 3 = D1; codeword P1 P2 D1 P4 D2 D3 D4, MSB first
"""
import os
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, "/home/<user>/medsciot")
import ecc_pipeline as E                                    # noqa: E402

N_SHOW = 50
SEED = 2026

M = E.load_nodes()
T = M["T"]

# ---------------- 50 test flows: 10 per class (stratified, fixed seed)
rng = np.random.default_rng(SEED)
per = N_SHOW // E.NUM_CLASSES
idx = np.concatenate([rng.choice(np.where(E.yte == c)[0], per, replace=False) for c in range(E.NUM_CLASSES)])
idx = rng.permutation(idx)
X = E.Xte[idx].astype(np.uint8)                               # (50, 178)
y = E.yte[idx].astype(np.uint8)
pred = E.fuse([s[idx] for s in M["clean_sums"]], T).astype(np.uint8)          # deployed model (4-bit weights)
pred_full = E.fuse([s[idx] for s in M["tmu_sums"]], M["T_full"]).astype(np.uint8)   # tmu, full integer weights
Xb = np.packbits(X, axis=1, bitorder="little")              # (50, 23)  feature f -> byte f//8, bit f%8

np.save(f"{HERE}/X_50.npy", X)
np.save(f"{HERE}/X_50_bitpacked.npy", Xb)
Xb.tofile(f"{HERE}/X_50.bin")
np.save(f"{HERE}/y_50_actual.npy", y.astype(np.uint32))
y.tofile(f"{HERE}/actual.bin")
np.save(f"{HERE}/y_50_tm_predictions.npy", pred.astype(np.uint32))
pred.tofile(f"{HERE}/tmu_pred.bin")
np.save(f"{HERE}/y_50_tm_predictions_fullweights.npy", pred_full.astype(np.uint32))
np.save(f"{HERE}/test_indices_in_medsec_testset.npy", idx)
np.save(f"{HERE}/class_names.npy", E.class_names)
with open(f"{HERE}/class_names.txt", "w") as f:
    for c, n in enumerate(E.class_names):
        f.write(f"{c} {n}\n")

# ---------------- split packet streams, one file per TM / sending RPi
counts = []
for n in range(E.N_NODES):
    for lay, tag in (("SEQ", "hamming"), ("none", "raw")):
        p = E.encode_node_file(n, M["cubes"][n], M["weights"][n], lay)
        data = np.fromfile(p, np.uint8)
        data.tofile(f"{HERE}/tm{n}_{tag}.bin")
    counts.append(len(M["schedules"][n]))

# ---------------- config header for the C receiver
with open(f"{HERE}/rpi_medsciot_config.h", "w") as f:
    f.write("/* generated by make_rpi_files.py - do not edit */\n#pragma once\n")
    f.write(f"#define NUM_NODES            {E.N_NODES}\n")
    f.write(f"#define NUM_CLASSES          {E.NUM_CLASSES}\n")
    f.write(f"#define INPUT_FEATURES       {E.O}\n")
    f.write(f"#define NUM_LITERALS         {E.L}\n")
    f.write(f"#define INPUT_BYTES          {Xb.shape[1]}\n")
    f.write(f"#define RULE_BYTES           {E.RULE_BYTES}\n")
    f.write(f"#define RULES_PER_PACKET     {E.RULES_PER_PACKET}\n")
    f.write(f"#define HEADER_BYTES         {E.HEADER_BYTES}\n")
    f.write(f"#define PAYLOAD_BYTES        {E.PAYLOAD_BYTES}\n")
    f.write(f"#define ENCODED_PAYLOAD      {E.ENC_PAYLOAD}\n")
    f.write(f"#define DATAGRAM_ENC         {E.DG_ENC}\n")
    f.write(f"#define DATAGRAM_RAW         {E.DG_RAW}\n")
    f.write(f"#define CLASS_SUM_T          {T}\n")
    f.write(f"#define NUM_INPUTS           {N_SHOW}\n")
    f.write(f"static const int PACKETS_PER_NODE[NUM_NODES] = {{{', '.join(map(str, counts))}}};\n")

acc = (pred == y).mean() * 100
print(f"50 test flows: classes {np.bincount(y, minlength=E.NUM_CLASSES).tolist()}  "
      f"deployed-model accuracy {acc:.1f} %  (full-weight tmu agrees on {(pred == pred_full).sum()}/50)")
print(f"packets per TM: {counts}  ({E.DG_ENC} B with Hamming, {E.DG_RAW} B raw)   T = {T}")
